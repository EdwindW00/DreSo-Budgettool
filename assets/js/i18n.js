function getLang() {
  return localStorage.getItem("dreso.lang.v1") || DEFAULT_LANG;
}

function setLang(lang) {
  if (!LANGUAGES[lang]) lang = DEFAULT_LANG;
  localStorage.setItem("dreso.lang.v1", lang);
  applyDocumentDirection(lang);
}

function applyDocumentDirection(lang) {
  const info = LANGUAGES[lang] || LANGUAGES[DEFAULT_LANG];
  document.documentElement.lang = lang;
  document.documentElement.dir = info.dir;
}

// vertaal een sleutel, met optionele {var}-interpolatie; valt terug op NL, dan op de sleutel zelf
function t(key, vars) {
  const lang = getLang();
  let str = (I18N[lang] && I18N[lang][key]) || I18N[DEFAULT_LANG][key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), vars[k]);
    });
  }
  return str;
}
